export function translate(lang: Lang, key: DictKey, vars?: Record<string, string | number>): string {
  const entry = D[key] as readonly string[] | undefined;
  let s = entry ? entry[IDX[lang]] ?? entry[0] : String(key);
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
  return s;
}
export type TFn = (key: DictKey, vars?: Record<string, string | number>) => string;
export const makeT = (lang: Lang): TFn => (key, vars) => translate(lang, key, vars);

/** Translate an API error code (e.g. "TENANT_SUSPENDED") or fall back to a generic message. */
export function errorText(lang: Lang, code: unknown): string {
  const k = `err_${String(code)}` as DictKey;
  return k in D ? translate(lang, k) : translate(lang, "errorGeneric");
}
export function hasKey(k: string): k is DictKey { return k in D; }
